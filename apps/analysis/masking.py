"""Маскирование персональных данных перед сохранением (задание 16, п. 4; раздел 2.7 ТЗ).

Без согласия пользователя полный текст не хранится, а в `input_masked` номера банковских карт (13–19 цифр),
телефонов и денежные суммы заменяются на `***`.
"""
from __future__ import annotations

import re

MASK = "***"

# Номер карты: 13–19 цифр, допускаются пробелы и дефисы между группами
_CARD_RE = re.compile(r"(?<![\d*])(?:\d[ \-]?){12,18}\d(?![\d*])")

# Телефон: +7 / 8 / код страны, затем 10 цифр в любом распространённом формате; либо 10–12 цифр подряд
_PHONE_RE = re.compile(
    r"(?<![\w*])(?:\+\d{1,3}|8)[\s\-]?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?![\d*])"
    r"|(?<![\d*])\d{10,12}(?![\d*])"
)

_CURRENCY = r"(?:₸|тг\.?|тенге|теңге|T\b|KZT|руб(?:\.|лей|ля|ль)?|₽|р\.|USD|EUR|€|\$|долл(?:\.|аров|ара)?|dollars?|сом)"
_NUMBER = r"\d{1,3}(?:[  .,]\d{3})+(?:[.,]\d{1,2})?|\d+(?:[.,]\d{1,2})?"
# Сумма: число с валютой (до или после), либо число с разделителем тысяч («50 000», «1,000»)
_MONEY_RE = re.compile(
    rf"(?:{_CURRENCY})\s?(?:{_NUMBER})"
    rf"|(?:{_NUMBER})\s?(?:{_CURRENCY})"
    r"|(?<![\d*])\d{1,3}(?:[  ,]\d{3})+(?![\d*])",
    re.IGNORECASE,
)


def mask_text(text: str) -> str:
    """Заменяет карты, телефоны и суммы на ***. Порядок важен: сначала длинные номера карт."""
    if not text:
        return text
    text = _CARD_RE.sub(MASK, text)
    text = _PHONE_RE.sub(MASK, text)
    text = _MONEY_RE.sub(MASK, text)
    return text
